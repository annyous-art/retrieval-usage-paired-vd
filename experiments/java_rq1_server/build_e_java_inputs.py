"""Inputs for running mode E (CWE entries, code query) on the MegaVul Java pairs with e_arm.py.

- cwe_entries.jsonl: CWE 4.20 entries in the same format as data/e_retrieval/cwe_entries.jsonl
  (prompt_full / prompt_short built by build_e_retrieval.load_cwe), with the Java platform filter of
  e_cwe_code_java.py instead of the C/C++ one.
- retrieval_cwe_code.jsonl: the server's code-query retrieval (out/java_e/e_cwe_code.jsonl), keyed by
  the row_id of the Java fixed-candidate targets (outdir/java_fc_*/targets.jsonl) as e_arm.py expects.
- cve_entries.jsonl: NVD descriptions (data/second_dataset/java_nvd_cve.jsonl) of the CVEs of the
  Java retrieval corpus (training split), without the test CVEs; prompt shows the description only.
- retrieval_cwe_desc.jsonl / retrieval_cve_desc.jsonl: description queries, as build_e_retrieval.py:
  the Vul-RAG purpose + function description generated by GPT-5.5
  (outdir/java_vulrag_queries_gpt-5.5/queries.json), SBERT all-mpnet-base-v2, top-10 stored.
Offline; no model calls.  Run from the repository root.
"""
import json, sys
from pathlib import Path
sys.path.insert(0, '.')
import build_e_retrieval as be
sys.path.insert(0, 'experiments/java_rq1_server')
from e_cwe_code_java import applies_to_java

OUT = Path('data/e_retrieval_java'); OUT.mkdir(parents=True, exist_ok=True)
be.applies_to_c = applies_to_java  # same entry format, Java platform filter
version, rows = be.load_cwe('data/e_retrieval/cwec_v4.20.xml')
with open(OUT / 'cwe_entries.jsonl', 'w') as f:
    for r in rows:
        f.write(json.dumps(r) + '\n')
ids = {r['id'] for r in rows}
row_of = {}
for model in ('gpt-5.5', 'glm-5.1'):
    for t in map(json.loads, open(f'outdir/java_fc_{model}/targets.jsonl')):
        assert row_of.setdefault(str(t['idx']), t['row_id']) == t['row_id']
ret = [json.loads(l) for l in open('out/java_e/e_cwe_code.jsonl')]
assert {str(r['idx']) for r in ret} == set(row_of), 'retrieval and targets cover different functions'
missing = {i for r in ret for i in r['ids'][:3]} - ids
assert not missing, f'retrieved entries without text: {sorted(missing)[:10]}'
with open(OUT / 'retrieval_cwe_code.jsonl', 'w') as f:
    for r in sorted(ret, key=lambda r: row_of[str(r['idx'])]):
        f.write(json.dumps({'row_id': row_of[str(r['idx'])], 'ids': r['ids'], 'scores': r['scores']}) + '\n')
# description-query variants (X3, X4)
nvd = {r['cve']: be.clean(r['description']) for r in map(json.loads, open('data/second_dataset/java_nvd_cve.jsonl')) if r.get('found') and r.get('description')}
test_cves = {json.loads(l).get('cve') for l in open('data/second_dataset/megavul_java_test_paired_labeled.jsonl')}
train_cves = sorted({json.loads(l).get('cve') for l in open('data/second_dataset/megavul_java_train_paired_labeled.jsonl')} - test_cves - {None})
cve = [{'id': c, 'description': nvd[c], 'prompt_full': f'Vulnerability description: {nvd[c]}', 'embed_text': nvd[c]} for c in train_cves if c in nvd]
with open(OUT / 'cve_entries.jsonl', 'w') as f:
    for r in cve:
        f.write(json.dumps(r, ensure_ascii=False) + '\n')
desc = {row_of[str(q['row_id'])]: be.clean(q['purpose']).strip('"') + '\n' + q['function']
        for q in json.load(open('outdir/java_vulrag_queries_gpt-5.5/queries.json'))}
assert set(desc) == set(row_of.values()), 'descriptions must cover every target row'
rws = sorted(desc)
q = be.encode_sbert([desc[r] for r in rws], 'sentence-transformers/all-mpnet-base-v2')
for name, corpus in (('cwe_desc', rows), ('cve_desc', cve)):
    d = be.encode_sbert([c['embed_text'] for c in corpus], 'sentence-transformers/all-mpnet-base-v2')
    with open(OUT / f'retrieval_{name}.jsonl', 'w') as f:
        for r, x in zip(rws, be.topn(q, d, [c['id'] for c in corpus])):
            f.write(json.dumps({'row_id': r, **x}) + '\n')
print(f'CVE corpus: {len(cve)} of {len(train_cves)} training CVEs have an NVD description; {len(rws)} description queries')
man = json.loads(open('out/java_e/manifest.json').read())
import hashlib
sha = lambda q: hashlib.sha256(q.read_bytes()).hexdigest()
man.update(outputs_sha256={n: sha(OUT / n) for n in ('cwe_entries.jsonl', 'cve_entries.jsonl', 'retrieval_cwe_code.jsonl', 'retrieval_cwe_desc.jsonl', 'retrieval_cve_desc.jsonl')},
           cve_entries=len(cve), text_model='sentence-transformers/all-mpnet-base-v2',
           entries_file_rows=len(rows), entries_version=version, source='out/java_e/e_cwe_code.jsonl', keyed_by='row_id of outdir/java_fc_*/targets.jsonl')
(OUT / 'manifest.json').write_text(json.dumps(man, indent=1))
print(f'CWE {version}: {len(rows)} Java entries; {len(ret)} retrieval rows; manifest entries {man["cwe_entries"]}')
