#!/usr/bin/env python3
"""Vul-RAG with another detector model: reuse the knowledge base and query descriptions of a finished run
and run only retrieval and detection with a new model (here GLM-5.1, knowledge from GPT-5.5).

The output directory must first be prepared with run.py prepare for the new model and provider (offline).
The knowledge-extraction stage is not run, so its offline capacity flags (training pairs whose extraction
prompt exceeds the new model's context) do not apply; retrieval audits every detection request against the
new model's context before any call, as run.py does. Everything else is run.py's own code: retrieve() and
detect() with the manifest protocol of the prepared directory (model, provider, temperature 0.01, top-k 20,
at most three knowledge items, early return, exhausted -1 mapped to NO).

Checks before importing: the source run was prepared from the same training pool, targets, and data files,
and its knowledge and query exports are complete. The imported files are copied byte for byte and their
hashes, with the source directory, are written to imported_from.json.

Usage (repository root, Vul-RAG environment):
  python experiments/vulrag_full/detect_with_imported_kb.py --source-run outdir/vulrag_gpt-5.5 \
      --out outdir/vulrag_glm-5.1_gpt55_knowledge --stage retrieve
  ... --stage detect --workers 4 [--max-calls 10]
"""
import argparse, fcntl, hashlib, json, shutil, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import run  # noqa: E402

sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--source-run', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--stage', choices=['retrieve', 'detect', 'score'], required=True)
    p.add_argument('--model', default='glm-5.1'); p.add_argument('--provider', default='uniapi')
    p.add_argument('--workers', type=int, default=4); p.add_argument('--max-calls', type=int, default=25000)
    a = p.parse_args()
    args = argparse.Namespace(model=a.model, provider=a.provider, out=a.out, workers=a.workers, max_output=16384,
                              temperature=0.01, read_timeout=900, max_attempts=3, max_calls=a.max_calls)
    manifest = run.load(a.out / 'manifest.json')
    if manifest['protocol'] != run.protocol(args):
        raise SystemExit('Prepared protocol differs from this invocation; no calls made')
    src = run.load(a.source_run / 'manifest.json')
    for k in ('pool_sha256', 'targets_sha256', 'train_file_sha256', 'test_file_sha256'):
        if src[k] != manifest[k]:
            raise SystemExit(f'Source run differs in {k}; no import')
    with (a.out / '.run.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        if a.stage == 'retrieve':
            for name in ('knowledge.json', 'queries.json'):
                shutil.copyfile(a.source_run / name, a.out / name)
            run.atomic(a.out / 'imported_from.json', {
                'source_run': str(a.source_run), 'source_model': src['protocol']['model'],
                'knowledge_sha256': sha(a.out / 'knowledge.json'), 'queries_sha256': sha(a.out / 'queries.json'),
                'note': 'knowledge base and query descriptions generated by the source run; only retrieval and detection run with ' + a.model})
            run.retrieve(args)
            same = run.load(a.out / 'retrieved.json') == run.load(a.source_run / 'retrieved.json')
            print('retrieved.json identical to the source run:', same, flush=True)
        elif a.stage == 'detect':
            imp = run.load(a.out / 'imported_from.json')
            if imp['knowledge_sha256'] != sha(a.out / 'knowledge.json') or imp['queries_sha256'] != sha(a.out / 'queries.json'):
                raise SystemExit('Imported files changed; no calls made')
            run.detect(args, manifest)
        else:
            run.score(args)


if __name__ == '__main__':
    main()
